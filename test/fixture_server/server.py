"""Replay (or record) Pub/Sub and Cloud Monitoring REST responses for the SQL tests.

    python3 test/fixture_server/server.py                          # replay
    python3 test/fixture_server/server.py --record http://127.0.0.1:18085
    python3 test/fixture_server/server.py --live http://127.0.0.1:18085   # no replay for vgi-test

Prints ``PORT:<n>`` on stdout once listening (ci/run-integration.sh waits for
it).

``recorded.json`` holds responses captured from the real Pub/Sub emulator
(test/fixture/run-emulator.sh) through this server in --record mode.
Temporary subscriptions in project ``prod-shop`` are simulated (see
Handler.simulate) so read_messages answers any arguments there.
``handwritten.json`` (generated by make_handwritten.py) holds documented REST
shapes the emulator cannot produce: IAM policies, Cloud Monitoring time
series, Protocol Buffer schemas, push / BigQuery / Cloud Storage
subscriptions, import topics, permission errors and the OAuth token endpoint
used by service-account keys.

Keys are ``METHOD path?sorted-query body`` with the JSON body canonicalized.

Temporary subscriptions (``vgi-temp-<time>-<random>``) get a different name
on every run, so their name is replaced by ``vgi-temp-*`` in keys, request
bodies and recorded responses, and every request on one temporary
subscription is keyed by the chain of requests made on it so far (a pull
after an ack is a different key from the first pull). Replayed responses get
the requested name substituted back in.

For Cloud Monitoring (``/v3/``) keys a request whose exact key is unknown is
also matched with its ``interval.*`` parameters removed, so calls whose
window defaults to "now" replay.

Environment:
  FIXTURE_FLAKY=1          answer every key with 429 + Retry-After: 0 once
  FIXTURE_REQUIRE_AUTH=1   demand "Authorization: Bearer test-token" (or the
                           token the fake /token endpoint issues): 401 otherwise
"""

import hashlib
import json
import os
import re
import sys
import threading
import urllib.error
import urllib.parse
import urllib.request

try:
    import fcntl  # only needed when recording (two servers write recorded.json)
except ImportError:  # Windows: replay only
    fcntl = None
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer

HERE = os.path.dirname(os.path.abspath(__file__))
RECORDED = os.path.join(HERE, "recorded.json")
HANDWRITTEN = os.path.join(HERE, "handwritten.json")

UPSTREAM = None
LIVE = False
if "--record" in sys.argv:
    UPSTREAM = sys.argv[sys.argv.index("--record") + 1].rstrip("/")
if "--live" in sys.argv:  # forward every emulator-project request, save nothing
    UPSTREAM = sys.argv[sys.argv.index("--live") + 1].rstrip("/")
    LIVE = True

LOCK = threading.Lock()
TEMP = re.compile(r"vgi-temp-[a-z0-9-]+")
GOOD_TOKENS = {"Bearer test-token", "Bearer sa-token-from-jwt"}


def load(path):
    try:
        with open(path) as f:
            return json.load(f)
    except FileNotFoundError:
        return {}


FIXTURES = load(RECORDED)
HAND = load(HANDWRITTEN)
SEEN = set()
CHAINS = {}  # actual temp name -> digest of the requests made on it
SIM = {}  # prod-shop temp name -> simulated state


def _b64(text):
    import base64
    return base64.b64encode(text.encode()).decode()


PROD_MESSAGES = [
    {"data": _b64('{"payment_id":"p-1","amount_cents":1250}'), "attributes": {"event": "authorized", "currency": "USD"},
     "messageId": "9001", "publishTime": "2026-01-01T00:00:01.000Z", "orderingKey": "card-1"},
    {"data": _b64('{"payment_id":"p-1","amount_cents":1250}'), "attributes": {"event": "captured", "currency": "USD"},
     "messageId": "9002", "publishTime": "2026-01-01T00:00:05.000Z", "orderingKey": "card-1"},
    {"data": _b64('{"payment_id":"p-2","amount_cents":999}'), "attributes": {"event": "authorized", "currency": "EUR"},
     "messageId": "9003", "publishTime": "2026-01-01T00:01:00.000Z", "orderingKey": "card-2"},
]


def canonical_body(raw):
    if not raw:
        return ""
    try:
        return json.dumps(json.loads(raw), sort_keys=True, separators=(",", ":"))
    except ValueError:
        return raw.decode("utf-8", "replace")


def base_key(method, path, query, body):
    items = sorted(urllib.parse.parse_qsl(query, keep_blank_values=True))
    q = urllib.parse.urlencode(items)
    return f"{method} {path}{'?' + q if q else ''} {body}".rstrip()


def strip_interval(query):
    items = [(k, v) for k, v in urllib.parse.parse_qsl(query, keep_blank_values=True) if not k.startswith("interval.")]
    return urllib.parse.urlencode(sorted(items))


def save(key, entry):
    """Merge one recording into recorded.json; two fixture servers record at once."""
    with LOCK:
        FIXTURES[key] = entry
        with open(RECORDED + ".lock", "w") as lk:
            if fcntl:
                fcntl.flock(lk, fcntl.LOCK_EX)
            current = load(RECORDED)
            current[key] = entry
            tmp = RECORDED + ".tmp"
            with open(tmp, "w") as f:
                json.dump(current, f, indent=1, sort_keys=True)
                f.write("\n")
            os.replace(tmp, RECORDED)


class Handler(BaseHTTPRequestHandler):
    protocol_version = "HTTP/1.1"

    def log_message(self, *args):
        pass

    def reply(self, status, body, headers=None):
        data = body if isinstance(body, bytes) else body.encode()
        self.send_response(status)
        self.send_header("Content-Type", "application/json")
        for k, v in (headers or {}).items():
            self.send_header(k, v)
        self.send_header("Content-Length", str(len(data)))
        self.end_headers()
        self.wfile.write(data)

    def gerror(self, code, status, msg):
        self.reply(code, json.dumps({"error": {"code": code, "message": msg, "status": status}}))

    def handle_any(self):
        n = int(self.headers.get("Content-Length") or 0)
        raw = self.rfile.read(n) if n else b""
        url = urllib.parse.urlsplit(self.path)

        # Fake OAuth token endpoint for service-account keys (JWT bearer grant).
        if url.path == "/token":
            form = urllib.parse.parse_qs(raw.decode())
            if form.get("grant_type") != ["urn:ietf:params:oauth:grant-type:jwt-bearer"] or not form.get("assertion"):
                self.reply(400, json.dumps({"error": "invalid_grant", "error_description": "bad assertion"}))
                return
            self.reply(200, json.dumps({"access_token": "sa-token-from-jwt", "token_type": "Bearer", "expires_in": 3600}))
            return

        if os.environ.get("FIXTURE_REQUIRE_AUTH") == "1" and self.headers.get("Authorization") not in GOOD_TOKENS:
            self.gerror(401, "UNAUTHENTICATED", "Request had invalid authentication credentials.")
            return

        method = self.command
        actual = TEMP.search(url.path)
        npath = TEMP.sub("vgi-temp-*", url.path)
        body = canonical_body(TEMP.sub("vgi-temp-*", raw.decode("utf-8", "replace")).encode()) if raw else ""
        key = base_key(method, npath, url.query, body)
        name = actual.group(0) if actual else None
        create = method == "PUT" and npath.endswith("/vgi-temp-*")
        if name:
            with LOCK:
                if create:
                    CHAINS[name] = ""
                key = key + " #" + CHAINS.get(name, "")

        if name and url.path.startswith("/v1/projects/prod-shop/"):
            self.simulate(method, url.path, name, raw)
            return

        # Creating a temporary subscription is never retried by the worker
        # (non-idempotent), so it is exempt from the 429-once mode.
        if os.environ.get("FIXTURE_FLAKY") == "1" and not create:
            with LOCK:
                first = key not in SEEN
                SEEN.add(key)
            if first:
                self.reply(429, json.dumps({"error": {"code": 429, "status": "RESOURCE_EXHAUSTED", "message": "slow down"}}),
                           {"Retry-After": "0"})
                return

        # While recording, requests on a temporary subscription always go
        # upstream: the subscription must really exist there for the steps
        # that follow, even when an identical read was recorded before.
        emu = url.path.startswith("/v1/projects/vgi-test/")
        entry = None if (UPSTREAM and name) or (LIVE and emu) else (HAND.get(key) or FIXTURES.get(key))
        if entry is None and url.path.startswith("/v3/"):
            alt = base_key(method, npath, strip_interval(url.query), body)
            entry = HAND.get(alt) or FIXTURES.get(alt)
        # Only the emulator's project is recorded; prod-shop and the other
        # hand-written projects must never be filled in from the emulator.
        if entry is None and UPSTREAM and emu:
            entry = self.forward(method, raw)
            if entry is not None and not LIVE:
                save(key, entry)
        if entry is None:
            sys.stderr.write(f"fixture: no response for {key}\n")
            self.gerror(404, "NOT_FOUND", f"fixture server has no recording for {key}")
            return
        if name:  # advance the chain only for answered requests
            with LOCK:
                CHAINS[name] = hashlib.sha1((CHAINS.get(name, "") + "|" + key).encode()).hexdigest()[:12]
        text = entry["body"]
        if name:
            text = text.replace("vgi-temp-*", name)
        self.reply(entry["status"], text, entry.get("headers"))

    def simulate(self, method, path, name, raw):
        """Hand-written temporary-subscription flow for project prod-shop.

        Unlike the recorded emulator flows (keyed by exact request chains),
        this answers any arguments, so agent tasks can call read_messages
        freely: create -> seek -> first pull returns PROD_MESSAGES (minus
        those excluded by an ``attributes.k = "v"`` filter) -> later pulls are
        empty -> acknowledge / delete succeed.
        """
        with LOCK:
            st = SIM.setdefault(name, {"pulled": False, "filter": None})
            if method == "PUT":
                body = json.loads(raw or b"{}")
                m = re.fullmatch(r'\s*attributes\.(\w+)\s*=\s*"([^"]*)"\s*', body.get("filter", "") or "")
                st["filter"] = m.groups() if m else None
                self.reply(200, json.dumps({"name": f"projects/prod-shop/subscriptions/{name}", "topic": body.get("topic")}))
                return
            if method == "POST" and path.endswith(":pull"):
                if st["pulled"]:
                    self.reply(200, "{}")
                    return
                st["pulled"] = True
                msgs = [m for m in PROD_MESSAGES
                        if not st["filter"] or m["attributes"].get(st["filter"][0]) == st["filter"][1]]
                rec = [{"ackId": f"projects/prod-shop/subscriptions/{name}:{i}", "message": m} for i, m in enumerate(msgs)]
                self.reply(200, json.dumps({"receivedMessages": rec} if rec else {}))
                return
            if method == "DELETE":
                SIM.pop(name, None)
        self.reply(200, "{}")

    def forward(self, method, raw):
        req = urllib.request.Request(UPSTREAM + self.path, data=raw or None, method=method)
        if raw:
            req.add_header("Content-Type", "application/json")
        try:
            with urllib.request.urlopen(req, timeout=60) as resp:
                status, data = resp.status, resp.read()
        except urllib.error.HTTPError as e:
            status, data = e.code, e.read()
        except OSError as e:
            sys.stderr.write(f"fixture: upstream error {e}\n")
            return None
        text = data.decode("utf-8", "replace")
        try:  # store compactly; keep the emulator's content
            text = json.dumps(json.loads(text), sort_keys=True) if text.strip() else ""
        except ValueError:
            pass
        return {"status": status, "body": TEMP.sub("vgi-temp-*", text)}

    do_GET = do_POST = do_PUT = do_DELETE = do_PATCH = handle_any


def main():
    srv = ThreadingHTTPServer(("127.0.0.1", 0), Handler)
    print(f"PORT:{srv.server_address[1]}", flush=True)
    srv.serve_forever()


if __name__ == "__main__":
    main()
